/**
 * @brief Application entry point
 * 
 * Initializes audio subsystem and starts processing loop
 */
void app_main(void) {
    ESP_LOGI(TAG, "========================================");
    ESP_LOGI(TAG, "ESP32 HVCC Audio Application Starting");
    ESP_LOGI(TAG, "========================================");
    
    // Initialize I2S hardware
    if (!audio_init_i2s()) {
        ESP_LOGE(TAG, "I2S initialization failed - halting");
        return;
    }
    
    // Initialize Heavy (Pure Data) audio engine
    if (!audio_init_heavy()) {
        ESP_LOGE(TAG, "Heavy initialization failed - halting");
        return;
    }
    
    // Initialize ADC and button controls
    bool adc_ok = audio_init_adc();
    bool btn_ok = controls_init_buttons();

    if (!adc_ok) {
        ESP_LOGW(TAG, "ADC initialization failed - knob controls may not work");
    }
    if (!btn_ok) {
        ESP_LOGW(TAG, "Button initialization failed - button controls may not work");
    }

    if (adc_ok || btn_ok) {
        // Start control input task with Heavy context
        xTaskCreate(control_task, "controls", 2048, audio_sys.heavy_context, 5, NULL);
    } else {
        ESP_LOGW(TAG, "No controls initialized - skipping controls task");
    }
    
    // Load OLED configuration and initialize display
    if (load_oled_config() && oled_init(&oled_config)) {
        ESP_LOGI(TAG, "OLED display initialized - starting update task");
        xTaskCreate(oled_task, "oled_display", 4096, NULL, 3, NULL);
    } else {
        ESP_LOGW(TAG, "OLED initialization failed - display will not be available");
    }

    // Load MIDI configuration and initialize
    if (load_midi_config() && midi_init(&midi_config, audio_sys.heavy_context)) {
        ESP_LOGI(TAG, "MIDI initialized successfully");
        // Set send hook to handle MIDI output from Pure Data
        hv_setSendHook(audio_sys.heavy_context, heavy_send_hook);
    } else {
        ESP_LOGI(TAG, "MIDI not configured or initialization failed");
    }
    
    ESP_LOGI(TAG, "All systems ready - starting audio output");
    ESP_LOGI(TAG, "========================================");
    
    // Run audio loop (never returns)
    audio_processing_loop();
}
