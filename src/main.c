static hv_uint32_t oled_table_hashes[OLED_MAX_DISPLAYS] = {0};

// MIDI configuration loaded from JSON
static midi_config_t midi_config = {0};

/**
 * @brief Load MIDI configuration from embedded board_config.json
 */
static bool load_midi_config(void) {
    extern const char board_config_json_start[];
    cJSON *root = cJSON_Parse(board_config_json_start);
    if (!root) {
        ESP_LOGE(TAG, "Failed to parse board_config for MIDI");
        return false;
    }

    cJSON *midi = cJSON_GetObjectItem(root, "midi");
    if (!midi) {
        ESP_LOGI(TAG, "No MIDI configuration found in board_config");
        cJSON_Delete(root);
        return false;
    }

    // Parse transport type
    cJSON *transport = cJSON_GetObjectItem(midi, "transport");
    if (transport && cJSON_IsString(transport)) {
        const char *transport_str = transport->valuestring;
        if (strcmp(transport_str, "uart") == 0) {
            midi_config.transport = MIDI_TRANSPORT_UART;
        } else if (strcmp(transport_str, "usb") == 0) {
            midi_config.transport = MIDI_TRANSPORT_USB;
        } else {
            midi_config.transport = MIDI_TRANSPORT_NONE;
        }
    }

    // Parse UART pins
    cJSON *uart_tx = cJSON_GetObjectItem(midi, "uart_tx_pin");
    cJSON *uart_rx = cJSON_GetObjectItem(midi, "uart_rx_pin");
    if (uart_tx && cJSON_IsNumber(uart_tx)) {
        midi_config.uart_tx_pin = uart_tx->valueint;
    }
    if (uart_rx && cJSON_IsNumber(uart_rx)) {
        midi_config.uart_rx_pin = uart_rx->valueint;
    }

    // Parse enable flags
    cJSON *enable_input = cJSON_GetObjectItem(midi, "enable_input");
    cJSON *enable_output = cJSON_GetObjectItem(midi, "enable_output");
    midi_config.enable_input = (enable_input && cJSON_IsBool(enable_input)) ? cJSON_IsTrue(enable_input) : false;
    midi_config.enable_output = (enable_output && cJSON_IsBool(enable_output)) ? cJSON_IsTrue(enable_output) : false;

    cJSON_Delete(root);

    ESP_LOGI(TAG, "MIDI config loaded: transport=%d, TX=%d, RX=%d, in=%d, out=%d",
             midi_config.transport, midi_config.uart_tx_pin, midi_config.uart_rx_pin,
             midi_config.enable_input, midi_config.enable_output);
    return true;
}

/**
 * @brief Load OLED configuration from embedded board_config.json
 */
extern const char board_config_json_start[];
extern const char board_config_json_end[];

static bool load_oled_config(void) {
    const char *json_str = board_config_json_start;
    size_t json_len = strlen(json_str);
    
    ESP_LOGI(TAG, "Loading OLED config from JSON (%u bytes)...", json_len);
    
    cJSON *root = cJSON_ParseWithLength(json_str, json_len);
    if (!root) {
        ESP_LOGE(TAG, "Failed to parse board_config.json");
        return false;
    }
    
    cJSON *oled = cJSON_GetObjectItem(root, "oled");
    if (!oled) {
        ESP_LOGW(TAG, "No 'oled' section in config - using defaults");
        cJSON_Delete(root);
        return false;
    }
    
    // Parse SPI pins
    cJSON *spi = cJSON_GetObjectItem(oled, "spi");
    if (spi) {
        oled_config.mosi_pin = cJSON_GetObjectItem(spi, "mosi")->valueint;
        oled_config.clk_pin = cJSON_GetObjectItem(spi, "clk")->valueint;
        oled_config.dc_pin = cJSON_GetObjectItem(spi, "dc")->valueint;
        oled_config.rst_pin = cJSON_GetObjectItem(spi, "rst")->valueint;
    } else {
        ESP_LOGE(TAG, "Missing 'spi' section in OLED config");
        cJSON_Delete(root);
        return false;
    }
    
    // Parse displays
    cJSON *displays = cJSON_GetObjectItem(oled, "displays");
    if (!displays || !cJSON_IsArray(displays)) {
        ESP_LOGE(TAG, "Missing or invalid 'displays' array");
        cJSON_Delete(root);
        return false;
    }
    
    int num_displays = cJSON_GetArraySize(displays);
    if (num_displays > OLED_MAX_DISPLAYS) {
        num_displays = OLED_MAX_DISPLAYS;
    }
    oled_config.num_displays = num_displays;
    
    for (int i = 0; i < num_displays; i++) {
        cJSON *disp = cJSON_GetArrayItem(displays, i);
        oled_display_config_t *disp_cfg = &oled_config.displays[i];
        
        disp_cfg->id = cJSON_GetObjectItem(disp, "id")->valueint;
        disp_cfg->cs_pin = cJSON_GetObjectItem(disp, "cs_pin")->valueint;
        
        // Parse value_min and value_max for scaling (optional, defaults to 0 and 1)
        cJSON *value_min_item = cJSON_GetObjectItem(disp, "value_min");
        cJSON *value_max_item = cJSON_GetObjectItem(disp, "value_max");
        disp_cfg->value_min = (value_min_item) ? (float)value_min_item->valuedouble : 0.0f;
        disp_cfg->value_max = (value_max_item) ? (float)value_max_item->valuedouble : 1.0f;
        
        cJSON *table_name = cJSON_GetObjectItem(disp, "table_name");
        if (table_name && cJSON_IsString(table_name) && table_name->valuestring) {
            strncpy(disp_cfg->table_name, table_name->valuestring, sizeof(disp_cfg->table_name) - 1);
            disp_cfg->table_name[sizeof(disp_cfg->table_name) - 1] = '\0';
            
            // Pre-compute hash for this table
            if (disp_cfg->table_name[0] != '\0') {
                oled_table_hashes[i] = hv_stringToHash(disp_cfg->table_name);
                ESP_LOGI(TAG, "Display %d: table '%s' hash = 0x%08lx", 
                         i, disp_cfg->table_name, oled_table_hashes[i]);
            }
        } else {
            disp_cfg->table_name[0] = '\0';
        }
    }
    
    cJSON_Delete(root);
    
    ESP_LOGI(TAG, "OLED config loaded: %d display(s)", oled_config.num_displays);
    return true;
}

